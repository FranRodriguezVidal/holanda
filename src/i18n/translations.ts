export const getDefaultLocale = (): Locale => {
  if (typeof navigator === 'undefined') {
    return 'en';
  }

  const browserLanguage = navigator.language.toLowerCase();
  return browserLanguage.startsWith('es') ? 'es' : 'en';
};
